class SqlAlchemyAssignmentRepository(BaseSqlAlchemyRepository[WorkAssignment, EmployeeWorkHistoryModel], AssignmentRepositoryInterface):
    """
    SQLAlchemy implementation of the AssignmentRepository interface.
    """

    def __init__(self, session: Session):
        """
        Initialize the repository with a SQLAlchemy session.

        Args:
            session: The SQLAlchemy session to use for database operations.
        """
        super().__init__(session, EmployeeWorkHistoryModel, WorkAssignment)
        self.logger = get_logger("heijunka.repositories.assignment")
        self.rate_limited_logger = get_logger("heijunka.repositories.assignment", rate_limit=True)

    @contextmanager
    def session_scope(self) -> Generator[Session, None, None]:
        """
        Provide a transactional scope around a series of operations.

        Yields:
            The SQLAlchemy session.
        """
        try:
            yield self._session
            self._session.commit()
        except SQLAlchemyError as e:
            self._session.rollback()
            error_msg = sanitize_exception(e)
            self.logger.error(
                f"Database operation failed: {error_msg}",
                extra={
                    "event_type": "database_error",
                    "error_type": type(e).__name__,
                    "repository": "assignment"
                }
            )
            raise RepositoryError(f"Database error: {error_msg}")
        except Exception as e:
            self._session.rollback()
            error_msg = sanitize_exception(e)
            self.logger.error(
                f"Unexpected error in assignment repository: {error_msg}",
                extra={
                    "event_type": "unexpected_error",
                    "error_type": type(e).__name__,
                    "repository": "assignment"
                }
            )
            raise RepositoryError(f"Repository error: {error_msg}")

    def delete_existing_entries_for_date(self, date, session=None) -> int:
        """
        Delete all existing work history entries for a specific date.

        This method only deletes entries that were generated by the scheduler and are not temporary.

        Args:
            date: The date for which to delete entries.
            session: Optional SQLAlchemy session to use. If not provided, a new session will be created.

        Returns:
            The number of entries deleted.
        """
        self.logger.info(
            f"Deleting existing work history entries for date: {date}",
            extra={
                "event_type": "work_history_entries_deletion",
                "date": date.isoformat() if hasattr(date, 'isoformat') else str(date)
            }
        )

        try:
            # Use the provided session or create a new one
            if session is None:
                use_session_scope = True
                session_context = self.session_scope()
                session = session_context.__enter__()
            else:
                use_session_scope = False

            try:
                # Find all entries for the given date that were generated by the scheduler and are not temporary
                query = session.query(EmployeeWorkHistoryModel).filter(
                    EmployeeWorkHistoryModel.worked_date == date,
                    EmployeeWorkHistoryModel.is_generated == True,
                    EmployeeWorkHistoryModel.is_temporary == False
                )

                # Get the count before deleting
                count = query.count()

                self.logger.info(
                    f"Found {count} entries to delete for date: {date}",
                    extra={
                        "event_type": "work_history_entries_found",
                        "date": date.isoformat() if hasattr(date, 'isoformat') else str(date),
                        "count": count
                    }
                )

                if count > 0:
                    # Delete the entries
                    query.delete(synchronize_session='fetch')

                    # Flush the session to ensure the delete operation is executed
                    session.flush()

                    self.logger.info(
                        f"Successfully deleted {count} work history entries for date: {date}",
                        extra={
                            "event_type": "work_history_entries_deletion_success",
                            "date": date.isoformat() if hasattr(date, 'isoformat') else str(date),
                            "count": count
                        }
                    )
                else:
                    self.logger.info(
                        f"No work history entries found to delete for date: {date}",
                        extra={
                            "event_type": "work_history_entries_deletion_skipped",
                            "date": date.isoformat() if hasattr(date, 'isoformat') else str(date),
                            "reason": "no_entries_found"
                        }
                    )

                # If we created a new session, commit it
                if use_session_scope:
                    session_context.__exit__(None, None, None)

                return count
            except Exception as e:
                # If we created a new session, roll it back
                if use_session_scope:
                    session_context.__exit__(type(e), e, e.__traceback__)
                raise
        except RepositoryError:
            # This will be caught and logged by session_scope
            raise
        except Exception as e:
            error_msg = sanitize_exception(e)
            self.logger.error(
                f"Error deleting work history entries for date: {error_msg}",
                extra={
                    "event_type": "work_history_entries_deletion_error",
                    "date": date.isoformat() if hasattr(date, 'isoformat') else str(date),
                    "error_type": type(e).__name__
                }
            )
            raise RepositoryError(f"Error deleting work history entries: {error_msg}")

    def save_all(self, assignments: List[WorkAssignment]) -> bool:
        """
        Save a list of work assignments.

        This method first deletes any existing entries for the dates in the assignments
        to avoid duplicate schedules.

        Args:
            assignments: The list of work assignments to save.

        Returns:
            True if all assignments were saved successfully, False otherwise.
        """
        if not assignments:
            self.logger.info(
                "No assignments to save",
                extra={
                    "event_type": "assignments_save_skipped",
                    "reason": "no_assignments"
                }
            )
            return True

        self.logger.info(
            f"Saving {len(assignments)} work assignments",
            extra={
                "event_type": "assignments_save",
                "assignment_count": len(assignments)
            }
        )

        # Group assignments by date
        dates = set(assignment.period.date for assignment in assignments)

        self.logger.info(
            f"Assignments span {len(dates)} unique dates",
            extra={
                "event_type": "assignments_dates",
                "date_count": len(dates)
            }
        )

        # Delete existing entries for each date
        for date in dates:
            try:
                with self.session_scope() as session:
                    # Find all entries for the given date that were generated by the scheduler and are not temporary
                    query = session.query(EmployeeWorkHistoryModel).filter(
                        EmployeeWorkHistoryModel.worked_date == date,
                        EmployeeWorkHistoryModel.is_generated == True,
                        EmployeeWorkHistoryModel.is_temporary == False
                    )

                    # Get the count before deleting
                    count = query.count()

                    self.logger.info(
                        f"Found {count} entries to delete for date: {date}",
                        extra={
                            "event_type": "work_history_entries_found",
                            "date": date.isoformat() if hasattr(date, 'isoformat') else str(date),
                            "count": count
                        }
                    )

                    if count > 0:
                        # Delete the entries
                        query.delete(synchronize_session='fetch')

                        # Flush the session to ensure the delete operation is executed
                        session.flush()

                        self.logger.info(
                            f"Successfully deleted {count} work history entries for date: {date}",
                            extra={
                                "event_type": "work_history_entries_deletion_success",
                                "date": date.isoformat() if hasattr(date, 'isoformat') else str(date),
                                "count": count
                            }
                        )
                    else:
                        self.logger.info(
                            f"No work history entries found to delete for date: {date}",
                            extra={
                                "event_type": "work_history_entries_deletion_skipped",
                                "date": date.isoformat() if hasattr(date, 'isoformat') else str(date),
                                "reason": "no_entries_found"
                            }
                        )
            except Exception as e:
                error_msg = sanitize_exception(e)
                self.logger.error(
                    f"Error deleting work history entries for date: {error_msg}",
                    extra={
                        "event_type": "work_history_entries_deletion_error",
                        "date": date.isoformat() if hasattr(date, 'isoformat') else str(date),
                        "error_type": type(e).__name__
                    }
                )
                print(f"ERROR: Failed to delete entries for date {date} - {e}")
                # Continue with the next date
                continue

        # Add all new assignments in a single transaction
        try:
            with self.session_scope() as session:
                success_count = 0
                missing_count = 0
                failed_assignments = []

                # Check which assignments are missing from the database
                print(f"DEBUG: Checking which assignments are missing from the database")
                for assignment in assignments:
                    # Check if this assignment already exists in the database
                    existing = session.query(EmployeeWorkHistoryModel).filter(
                        EmployeeWorkHistoryModel.employee_id == assignment.employee.id,
                        EmployeeWorkHistoryModel.station_id == assignment.workstation.id,
                        EmployeeWorkHistoryModel.worked_date == assignment.period.date,
                        EmployeeWorkHistoryModel.work_period == assignment.period.period
                    ).first()

                    if existing is None:
                        if missing_count < 5:
                            print(f"  Missing: Employee ID: {assignment.employee.id} ({assignment.employee.name}), " +
                                  f"Workstation ID: {assignment.workstation.id} ({assignment.workstation.name}), " +
                                  f"Date: {assignment.period.date}, Period: {assignment.period.period}")
                        elif missing_count == 5:
                            print(f"  ... and {len(assignments) - 5} more missing assignments")
                        missing_count += 1

                # Add all assignments to the database
                for assignment in assignments:
                    try:
                        # Convert domain entity to model using the _to_model method
                        model = self._to_model(assignment)
                        session.add(model)
                        success_count += 1

                        # Print detailed information for debugging (only for the first few)
                        if success_count <= 5:
                            print(f"DEBUG: Adding assignment - Employee: {assignment.employee.id} ({assignment.employee.name}), " +
                                f"Workstation: {assignment.workstation.id} ({assignment.workstation.name}), " +
                                f"Team: {assignment.workstation.team_id}, " +
                                f"Date: {assignment.period.date}, Period: {assignment.period.period}")

                        self.rate_limited_logger.debug(
                            f"Added assignment for employee {assignment.employee.id} at workstation {assignment.workstation.id}",
                            event_type="assignment_added",
                            identifier=f"{assignment.employee.id}_{assignment.workstation.id}_{assignment.period.date}_{assignment.period.period}",
                            extra={
                                "employee_id": assignment.employee.id,
                                "workstation_id": assignment.workstation.id,
                                "date": assignment.period.date.isoformat() if hasattr(assignment.period.date, 'isoformat') else str(assignment.period.date),
                                "period": assignment.period.period
                            }
                        )
                    except Exception as e:
                        # Log the error but continue with other assignments
                        error_msg = sanitize_exception(e)
                        print(f"ERROR: Failed to add assignment - Employee: {assignment.employee.id}, Workstation: {assignment.workstation.id} - {e}")
                        self.logger.error(
                            f"Error adding assignment: {error_msg}",
                            extra={
                                "event_type": "assignment_add_error",
                                "employee_id": assignment.employee.id,
                                "workstation_id": assignment.workstation.id,
                                "date": assignment.period.date.isoformat() if hasattr(assignment.period.date, 'isoformat') else str(assignment.period.date),
                                "period": assignment.period.period,
                                "error_type": type(e).__name__
                            }
                        )
                        failed_assignments.append(assignment)

                # Flush the session to ensure all operations are executed
                session.flush()

                # Verify that all assignments were saved
                verification_count = 0
                for assignment in assignments:
                    if assignment not in failed_assignments:
                        # Check if this assignment exists in the database
                        existing = session.query(EmployeeWorkHistoryModel).filter(
                            EmployeeWorkHistoryModel.employee_id == assignment.employee.id,
                            EmployeeWorkHistoryModel.station_id == assignment.workstation.id,
                            EmployeeWorkHistoryModel.worked_date == assignment.period.date,
                            EmployeeWorkHistoryModel.work_period == assignment.period.period
                        ).first()

                        if existing is not None:
                            verification_count += 1

                self.logger.info(
                    f"Successfully saved {verification_count} of {len(assignments)} work assignments in a single transaction",
                    extra={
                        "event_type": "assignments_save_success",
                        "assignment_count": verification_count,
                        "total_assignments": len(assignments),
                        "failed_assignments": len(failed_assignments)
                    }
                )

                if verification_count != len(assignments):
                    self.logger.warning(
                        f"Not all assignments were saved to the database. Expected: {len(assignments)}, Actual: {verification_count}",
                        extra={
                            "event_type": "assignments_save_incomplete",
                            "expected": len(assignments),
                            "actual": verification_count
                        }
                    )
                    print(f"WARNING: Only {verification_count} of {len(assignments)} assignments were saved to the database.")

                return verification_count == len(assignments)

        except Exception as e:
            # Print the error for debugging
            error_msg = sanitize_exception(e)
            print(f"ERROR: Failed to add assignments in batch - {e}")
            self.logger.error(
                f"Error saving assignments in batch: {error_msg}",
                extra={
                    "event_type": "assignments_save_error",
                    "error_type": type(e).__name__
                }
            )
            return False

    def get_by_employee_id(self, employee_id: int) -> List[WorkAssignment]:
        """
        Retrieve all assignments for a specific employee.

        Args:
            employee_id: The ID of the employee.

        Returns:
            A list of work assignments for the employee.
        """
        self.logger.info(
            f"Retrieving assignments for employee ID: {employee_id}",
            extra={
                "event_type": "assignments_lookup",
                "lookup_type": "employee_id",
                "employee_id": employee_id
            }
        )

        try:
            models = self._session.query(EmployeeWorkHistoryModel).filter(
                EmployeeWorkHistoryModel.employee_id == employee_id
            ).all()

            assignment_count = len(models)
            self.logger.info(
                f"Found {assignment_count} assignments for employee ID: {employee_id}",
                extra={
                    "event_type": "assignments_lookup_success",
                    "lookup_type": "employee_id",
                    "employee_id": employee_id,
                    "assignment_count": assignment_count
                }
            )

            return [self._to_domain(model) for model in models]
        except SQLAlchemyError as e:
            error_msg = sanitize_exception(e)
            self.logger.error(
                f"Error retrieving assignments for employee: {error_msg}",
                extra={
                    "event_type": "assignments_lookup_error",
                    "lookup_type": "employee_id",
                    "employee_id": employee_id,
                    "error_type": type(e).__name__
                }
            )
            raise RepositoryError(f"Database error while retrieving assignments: {error_msg}")
        except Exception as e:
            error_msg = sanitize_exception(e)
            self.logger.error(
                f"Unexpected error retrieving assignments for employee: {error_msg}",
                extra={
                    "event_type": "assignments_lookup_error",
                    "lookup_type": "employee_id",
                    "employee_id": employee_id,
                    "error_type": type(e).__name__
                }
            )
            raise RepositoryError(f"Error retrieving assignments: {error_msg}")

